from typing import Dict, Any
from app.agents.state import AgentWorkflowState
from app.integrations.github import GitHubClient


async def pull_request_node(state: AgentWorkflowState) -> Dict[str, Any]:
    """Node for generating Pull Request details and coordinating authorized submission."""
    change = state.get("change_data") or {}
    plan = state.get("plan_data") or {}
    test_results = state.get("test_results") or {}
    review = state.get("review_results") or {}
    events = list(state.get("events", []))

    title = f"fix: {plan.get('title', 'resolve issue')}"
    test_summary = f"- Total: {test_results.get('total_tests', 0)}\n- Passed: {test_results.get('passed_tests', 0)}\n- Status: {test_results.get('status', 'passed')}"
    review_score = review.get("quality_score", 95.0)

    body = (
        f"## Summary of Changes\n{change.get('summary', 'Automated solution generated by RepoPilot AI.')}\n\n"
        f"### Technical Implementation\n{plan.get('strategy_overview', 'Targeted code modification.')}\n\n"
        f"### Verification & Tests\n{test_summary}\n\n"
        f"### AI Code Review Quality\n- Quality Score: **{review_score}/100**\n- Status: **{review.get('overall_status', 'approved')}**\n\n"
        f"---\n*Generated by RepoPilot AI - Autonomous Open-Source Engineering Platform*"
    )

    sid = state.get("session_id", "patch")
    clean_sid = "".join(c for c in sid if c.isalnum())[:8] or "update"
    branch_name = f"repopilot/{clean_sid}"

    pr_data = {
        "title": title,
        "body": body,
        "source_branch": branch_name,
        "target_branch": state.get("default_branch", "main"),
        "state": "prepared",
    }

    events.append({
        "agent_name": "Pull Request Agent",
        "stage": "pr_prepared",
        "event_type": "step",
        "message": f"Prepared PR: '{title}' targeting branch '{state.get('default_branch', 'main')}'. Awaiting developer authorization.",
        "payload": {"branch": branch_name, "title": title},
    })

    return {
        "current_agent": "Pull Request Agent",
        "current_stage": "pr_ready",
        "pr_data": pr_data,
        "events": events,
        "status": "waiting_approval",
    }
