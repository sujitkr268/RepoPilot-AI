from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy import select
from sqlalchemy.orm import selectinload
from sqlalchemy.ext.asyncio import AsyncSession
from app.api.deps import get_current_user
from app.database.session import get_db
from app.models.user import User, GitHubAccount
from app.models.change import GeneratedChange
from app.models.plan import ImplementationPlan
from app.models.issue import Issue
from app.models.repository import Repository
from app.models.pull_request import PullRequest
from app.schemas.pull_request import PullRequestCreateRequest, PullRequestRead
from app.agents.nodes.pr_node import pull_request_node
from app.agents.state import AgentWorkflowState
from app.integrations.github import GitHubClient, GitHubAPIError

router = APIRouter(tags=["Pull Requests"])


@router.post("/changes/{change_id}/pull-request", response_model=PullRequestRead)
async def create_pull_request(
    change_id: str,
    payload: PullRequestCreateRequest,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """
    Prepares or opens a Pull Request on GitHub.
    Enforces mandatory developer confirmation gate (confirm_push must be true).
    """
    if not payload.confirm_push:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Explicit user confirmation required before creating branch or opening pull request.",
        )

    stmt = (
        select(GeneratedChange)
        .options(
            selectinload(GeneratedChange.plan)
            .selectinload(ImplementationPlan.issue)
            .selectinload(Issue.repository)
        )
        .where(GeneratedChange.id == change_id, GeneratedChange.user_id == current_user.id)
    )
    res = await db.execute(stmt)
    change = res.scalar_one_or_none()
    if not change:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Generated change not found.")

    repo = change.plan.issue.repository

    state: AgentWorkflowState = {
        "change_data": {"summary": change.summary},
        "plan_data": {"title": change.plan.title, "strategy_overview": change.plan.strategy_overview},
        "default_branch": repo.default_branch,
        "events": [],
    }

    result = await pull_request_node(state)
    pr_data = result.get("pr_data", {})

    source_branch = payload.branch_name or pr_data.get("source_branch", "repopilot/patch-1")
    title = payload.title or pr_data.get("title", f"fix: {change.title}")
    body = payload.body or pr_data.get("body", "PR generated by RepoPilot AI.")

    # Check for GitHub OAuth token to attempt real GitHub API creation if available
    acc_stmt = select(GitHubAccount).where(GitHubAccount.user_id == current_user.id)
    acc_res = await db.execute(acc_stmt)
    gh_acc = acc_res.scalar_one_or_none()

    github_pr_number = None
    html_url = None
    pr_state = "prepared"

    if gh_acc and gh_acc.access_token_encrypted:
        gh_client = GitHubClient(access_token=gh_acc.access_token_encrypted)
        try:
            gh_res = await gh_client.create_pull_request(
                owner=repo.owner,
                repo=repo.name,
                title=title,
                body=body,
                head_branch=source_branch,
                base_branch=payload.target_branch,
            )
            github_pr_number = gh_res.get("number")
            html_url = gh_res.get("html_url")
            pr_state = "created"
        except GitHubAPIError:
            # If repo is external or token doesn't have push access, keep as prepared
            pr_state = "prepared"
            html_url = f"https://github.com/{repo.owner}/{repo.name}/compare/{payload.target_branch}...{source_branch}"
    else:
        html_url = f"https://github.com/{repo.owner}/{repo.name}/compare/{payload.target_branch}...{source_branch}"

    pr = PullRequest(
        change_id=change.id,
        user_id=current_user.id,
        github_pr_number=github_pr_number,
        html_url=html_url,
        target_branch=payload.target_branch,
        source_branch=source_branch,
        title=title,
        body=body,
        state=pr_state,
        is_user_authorized=True,
    )
    db.add(pr)
    await db.commit()
    await db.refresh(pr)
    return pr


@router.get("/pull-requests/{id}", response_model=PullRequestRead)
async def get_pull_request(
    id: str,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    stmt = select(PullRequest).where(PullRequest.id == id, PullRequest.user_id == current_user.id)
    res = await db.execute(stmt)
    pr = res.scalar_one_or_none()
    if not pr:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Pull request record not found.")
    return pr
